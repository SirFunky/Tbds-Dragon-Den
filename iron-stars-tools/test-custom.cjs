const assert=require('node:assert/strict');
const fs=require('node:fs');
const custom=require('../iron-stars/assets/custom-core.js');
const roster=require('../iron-stars/assets/roster-core.js');
const data=JSON.parse(fs.readFileSync('iron-stars/data/army-builder.json','utf8'));
const part=(name,kind)=>data.custom.parts.find(p=>p.name===name&&p.kind===kind&&p.source_id==='core');
const chassis=part('Medium','chassis'),laser=part('Medium Laser','weapon'),jetpack=part('Jetpack','system');
const unit={name:'Test custom',chassis:chassis.id,movement:15,structure:4,weapons:[{component:laser.id,quantity:4,linked:true}],systems:[jetpack.id]};
assert.equal(custom.calculate(unit,'iron-concord',data).total,49);
assert.deepEqual(custom.calculate(unit,'iron-concord',data).breakdown[1].copy_prices,[6,6,6,12]);
assert.equal(custom.calculate({...unit,weapons:[unit.weapons[0],unit.weapons[0]],systems:[]},'iron-concord',data).total,75);
assert.equal(custom.calculate({...unit,weapons:[{...unit.weapons[0],linked:false}]},'iron-concord',data).total,43);
assert.equal(custom.calculate({...unit,structure:5},'iron-concord',data).total,49);
const linewalker=data.custom.parts.find(p=>p.name==='Linewalker'&&p.kind==='chassis');
assert.equal(custom.calculate({...unit,chassis:linewalker.id,movement:12.5,structure:3},'iron-concord',data).total,44);
for(const patch of [{structure:6},{movement:16},{name:''},{chassis:laser.id},{systems:[jetpack.id,jetpack.id]}])assert.throws(()=>custom.calculate({...unit,...patch},'iron-concord',data));
for(const quantity of [0,-1,1.5,100,'4',null])assert.throws(()=>custom.calculate({...unit,weapons:[{component:laser.id,quantity,linked:true}]},'iron-concord',data));
assert.throws(()=>custom.calculate({...unit,weapons:[{component:laser.id,quantity:1,linked:true}]},'iron-concord',data));
const blade=part('Light Blade','weapon');
assert.throws(()=>custom.calculate({...unit,weapons:[{component:blade.id,quantity:4,linked:true}]},'iron-concord',data));
const drone=part('Drone Logic','system');
assert.throws(()=>custom.calculate({...unit,systems:[drone.id]},'iron-concord',data));
assert.equal(custom.calculate({...unit,systems:[drone.id]},'cybernetic-rebellion',data).total,47);
assert.throws(()=>custom.calculate(unit,'southern-cross-compact',data));
const scrap=data.custom.parts.find(p=>p.name==='Scrap Rifle');
assert.throws(()=>custom.calculate({...unit,weapons:[{component:scrap.id,quantity:1,linked:false}]},'unmc',data));
const ammo=data.custom.parts.find(p=>p.requires_ammunition);
assert.throws(()=>custom.calculate({...unit,systems:[ammo.id]},'iron-concord',data));
// Source-backed Unique semantics must also hold if a second Unique system is added later.
const fixture=JSON.parse(JSON.stringify(data));
const unique={...jetpack,id:'unique-fixture',unique:true};fixture.custom.parts.push(unique);
assert.throws(()=>custom.calculate({...unit,systems:[ammo.id,unique.id],ammo_target:0},'iron-concord',fixture),/only one Unique/);
fixture.custom.parts.find(p=>p.id===laser.id).details.push({text:'Ammunition 2',label:'Test fixture'});
assert.equal(custom.calculate({...unit,systems:[ammo.id],ammo_target:0},'iron-concord',fixture).total,48);
let force=roster.saveCustom(roster.blank('iron-concord'),'custom-test',unit,data);
force=roster.add(force,'iron-concord-ironsworn-trooper',data);
force.lines[0].quantity=2;
assert.equal(roster.summarize(force,data).total,107);
assert.deepEqual(roster.decode(roster.encode(force,data),data),force);
const forged=JSON.parse(roster.encode(force,data));forged.lines[0].custom.price=0;forged.lines[0].custom.defence='1+';
assert.equal(roster.summarize(roster.decode(JSON.stringify(forged),data),data).total,107);
assert.equal(roster.resolve(roster.decode(JSON.stringify(forged),data).lines[0],'iron-concord',data).calculation.defence,'4+');
const updated=JSON.parse(JSON.stringify(data));updated.custom.parts.find(p=>p.id===laser.id).price=7;
assert.equal(roster.summarize(roster.decode(roster.encode(force,data),updated),updated).total,117);
force=roster.saveCustom(force,'custom-test',{...unit,name:'Edited',systems:[]},data);
assert.equal(force.lines[0].quantity,2);assert.equal(force.lines[0].custom.name,'Edited');
assert.equal(roster.summarize(force,data).total,99);
assert.throws(()=>roster.decode(JSON.stringify({...force,faction:'southern-cross-compact'}),data));
assert.throws(()=>roster.saveCustom(force,'iron-concord-ironsworn-trooper',unit,data));
const incomplete=JSON.parse(roster.encode(force,data));incomplete.lines[0].custom.weapons[0].component='unknown';
assert.throws(()=>roster.decode(JSON.stringify(incomplete),data));
assert(!custom.parts(data,'unmc','system').some(p=>p.name==='Command Network'));
assert(!data.custom.parts.some(p=>p.price===null||p.name==='Sponsor Protocol'));
assert.equal(new Set(data.custom.parts.map(p=>p.id)).size,data.custom.parts.length);
console.log('PASS: custom costs, independent linked groups, chassis bounds, faction locks, Unique and Ammo Bin rules, edit/quantity preservation, mixed rosters, current-price persistence and forged-cost rejection.');
